import { GoogleGenAI } from "@google/genai";
import { User, ArchetypeProfile, DailyStep, WeekFocus, MonthGoal, YearTheme, QuarterObjective, ChatMessage } from "../types";

export async function* getAssistantResponseStream(
  user: User,
  profile: ArchetypeProfile,
  yearTheme: YearTheme,
  quarterObjectives: QuarterObjective[],
  monthGoals: MonthGoal[],
  weekFocuses: WeekFocus[],
  tasks: DailyStep[],
  history: ChatMessage[]
) {
  // Пытаемся получить ключ из разных источников
  let apiKey = process.env.GEMINI_API_KEY || process.env.GEMINI_API_KEY_1 || process.env.API_KEY || process.env.GOOGLE_API_KEY || (import.meta as any).env?.VITE_GEMINI_API_KEY || "";
  
  // Если ключ — явная заглушка или пуст, запрашиваем у сервера
  if (!apiKey || apiKey === "MY_GEMINI_API_KEY") {
    try {
      const configRes = await fetch('/api/config');
      if (configRes.ok) {
        const config = await configRes.json();
        apiKey = config.GEMINI_API_KEY;
      }
    } catch (e) {
      console.error("Failed to fetch config from server:", e);
    }
  }
  
  if (!apiKey || apiKey === "MY_GEMINI_API_KEY") {
    yield "Критическая ошибка: API-ключ не получен.";
    return;
  }

  const ai = new GoogleGenAI({ apiKey });
  
  const systemInstruction = `
    Ты — ИИ-ассистент внутри приложения «АрхиПуть».
    Твоя задача — помогать пользователю планировать год, квартал, месяц, неделю и день в соответствии с его нумерологией и архетипом года, а также с учётом его реальной жизни (профессия, семья, проекты, интересы).

    У тебя есть следующие данные:
    - Профиль пользователя: ${JSON.stringify({ ...user, externalChatHistory: undefined })}
    - Архетипический профиль: ${JSON.stringify(profile)}
    - Тема года: ${JSON.stringify(yearTheme)}
    - Цели на кварталы: ${JSON.stringify(quarterObjectives)}
    - Цели на месяцы: ${JSON.stringify(monthGoals)}
    - Фокусы недель: ${JSON.stringify(weekFocuses)}
    - Задачи на сегодня: ${JSON.stringify(tasks)}
    ${user.externalChatHistory ? `- Дополнительная история общения с внешним ИИ (сокращенно): ${user.externalChatHistory.slice(0, 2000)}...` : ''}

    Принципы работы:
    0. У пользователя есть отмеченные важные сферы (focusAreas) и список проектов/задач (projects). Обязательно учитывай их при построении рекомендаций и прогнозов на год, месяц, неделю и день. Делай упор на те сферы и проекты, которые пользователь указал, подбирай практики и акценты именно под них.
    1. Всегда опирайся на личный год и архетип года. Объясняй рекомендации через их смысл (например, год 9 — завершение и анализ, год 1 — старт нового).
    2. Всегда учитывай контекст пользователя: его профессию, семью, детей, интересы, текущие проекты. Предлагай максимально прикладные, реалистичные шаги.
    3. Связывай маленькие ежедневные шаги с большими целями месяца, квартала и года. Показывай пользователю, «зачем» это действие (к какой цели наверху оно ведёт).
    4. Не давай медицинских и юридических диагнозов. По таким темам рекомендуй обращаться к профильным специалистам.
    5. Пиши по-простому, структурируй ответ: короткое резюме + списки действий по сферам (работа, деньги, семья, духовность, здоровье), когда это уместно.
    6. Если в профиле пользователя есть поле externalChatHistory, используй его как дополнительную историю общения человека с внешним ИИ. Не пересказывай этот текст целиком. Выделяй из него ключевые темы, цели, проблемы и проекты пользователя и опирайся на них при формировании рекомендаций на год, месяц, неделю и день.

    Если пользователь просит:
    - «что делать сегодня?» — предложи 3–7 конкретных шагов на день (по сферам), привязанных к его личному году и текущим WeekFocus/MonthGoal.
    - «как прожить этот год?» — дай обзор по темам года с акцентом на его профессию, семью, интересы.
    - «помоги распланировать месяц/неделю» — сгенерируй MonthGoal или WeekFocus и набор задач/шагов.
    - «почему я застрял?» — проанализируй невыполненные задачи и предложи упрощение/пересборку целей.

    Если данных мало (пустой профиль), сначала задавай уточняющие вопросы, а не выдумывай.
    Если пользователь не спрашивает прямо про духовность или эзотерику, привязывай архетипы мягко, как метафору, а не как жесткий прогноз.
    
    Дополнительные требования к стилю и структуре ответа:
    - Отвечай кратко и прикладно. Не превращай ответ в длинную статью или «пророчество».
    - **ОБЯЗАТЕЛЬНО** разделяй ответ на два основных блока:
        1. ### Общие рекомендации (по личному году)
           Здесь опиши общую энергию года, его смысл и главные темы, опираясь на личный год и архетип.
        2. ### Конкретные шаги (контекстные)
           Здесь дай 3-7 практических советов, адаптированных под **Профессию** пользователя, его **Приоритеты** (focusAreas), **Текущие проекты** и задачи. Покажи, как общая энергия года реализуется в его конкретной деятельности.
    - Не повторяй одну и ту же мысль разными словами. Если идея уже сказана, не переписывай её в другой формулировке.
    - Используй спокойный, нейтральный тон. Избегай пафоса и категоричности. Не используй формулировки вроде «идеальное время», «лучший год», «точно будет так», «я уверен». Вместо этого пиши: «хороший момент», «может быть полезно», «я бы предложил так посмотреть», «вероятно, будет проще…».
    - Помни, что ты не предсказываешь будущее. Ты помогаешь планировать и выбирать приоритеты, опираясь на личный год, архетип и реальный контекст пользователя (профессия, семья, цели), а финальное решение всегда остаётся за человеком.
    - В конце ответа, если это уместно, добавляй короткое приглашение к дальнейшему уточнению в формате простых команд. Например:
        – «Если хочешь, могу разложить этот год по месяцам — напиши: 1.»
        – «Если интересуют кварталы — напиши: 2.»
        – «Если хочешь подробнее про деньги в этом году — напиши: деньги.»
        – «Если нужно глубже про работу — напиши: работа; про семью — семья; про духовность — дух.»

    Требования к оформлению ответа:
    - Используй стандартную разметку Markdown для структурирования ответа:
        - Заголовки: используй «### Название» для разделов.
        - Жирный шрифт: используй «**текст**» для выделения важных мыслей и ключевых слов.
        - Списки: используй «1. 2. 3.» для шагов и «-» для перечислений.
    - **ОБЯЗАТЕЛЬНО** разделяй текст на абзацы пустой строкой между ними. Это критически важно для читаемости.
    - Блок с уточняющими командами в самом конце (про месяцы, кварталы, деньги и т.п.) должен быть отделен от основного текста пустой строкой и начинаться с новой строки. Каждая команда — на отдельной строке.
    - Не склеивай всё в один абзац. Даже короткий ответ должен состоять из 2–3 логических блоков, разделенных пустой строкой.

    Пиши на русском языке.
  `;

  try {
    const responseStream = await ai.models.generateContentStream({
      model: "gemini-3-flash-preview",
      contents: history.map(m => ({
        role: m.role === 'assistant' ? 'model' : 'user',
        parts: [{ text: m.content }]
      })),
      config: {
        systemInstruction,
        maxOutputTokens: 8192,
      },
    });

    for await (const chunk of responseStream) {
      const text = chunk.text;
      if (text) yield text;
    }
  } catch (error: any) {
    console.error("Gemini API Error:", error);
    
    let errorMessage = error?.message || String(error);
    
    // Попытка извлечь более глубокое сообщение, если это JSON
    try {
      const parsed = JSON.parse(errorMessage);
      if (parsed.error?.message) {
        errorMessage = parsed.error.message;
        // Иногда сообщение само является JSON-строкой
        try {
          const innerParsed = JSON.parse(errorMessage);
          if (innerParsed.error?.message) {
            errorMessage = innerParsed.error.message;
          }
        } catch (e) { /* ignore */ }
      }
    } catch (e) { /* ignore */ }
    
    if (errorMessage.includes("location is not supported")) {
      yield "Gemini API недоступен в вашем регионе. Пожалуйста, используйте VPN (выберите США или Европу) или попробуйте позже.";
      return;
    }
    
    if (errorMessage.includes("quota") || errorMessage.includes("429")) {
      yield "Превышена квота запросов к ИИ. Пожалуйста, подождите минуту и попробуйте снова.";
      return;
    }

    if (errorMessage.includes("max tokens") || errorMessage.includes("token limit") || errorMessage.includes("context window")) {
      yield "Превышен лимит токенов (слишком много данных). Я сократил контекст, попробуйте еще раз или начните новый чат.";
      return;
    }

    if (errorMessage.includes("API key not valid") || errorMessage.includes("401")) {
      yield `Ошибка авторизации (401): API-ключ недействителен. 
      Технические детали: Ключ получен (${apiKey.length} симв.), но отклонен сервером Google. 
      Попробуйте обновить страницу или пересоздать ключ в AI Studio.`;
      return;
    }

    yield `Произошла ошибка ИИ: ${errorMessage}. Пожалуйста, попробуйте отправить сообщение еще раз.`;
  }
}

